-- ============================================================================
-- 18. CATALOGO DE LABORATORIOS Y TALLERES
-- ============================================================================
-- Que hace:
--   Sustituye el booleano 'aulas.taller' ("es lab/taller, sin decir cual") por un
--   catalogo de tipos de espacio, uno por aula:
--     Laboratorio de Computo, Laboratorio de Quimica, Taller de Produccion,
--     Taller de Mecanica.
--   El catalogo es POR ESCUELA Y POR SEMESTRE, como el resto de catalogos, y es
--   editable: esos cuatro son solo los primeros, se pueden anadir mas.
--
-- Por que:
--   Un laboratorio de quimica y un taller de mecanica no son intercambiables en el
--   horario. Con un solo booleano el motor podia mover una practica de quimica a un
--   taller de mecanica y el horario quedaba formalmente valido pero inservible.
--   Ahora el tipo se declara EN EL AULA y el motor respeta el tipo al reasignar.
--
-- Que pasa con 'aulas.taller':
--   NO se elimina y NO lleva disparador. Se queda como columna normal y la mantiene
--   la aplicacion: AulaServicio pone taller = (tipo_espacio_id IS NOT NULL) en cada
--   alta y cada edicion, que es el unico sitio que escribe aulas.
--   Se evita el disparador a proposito, por dos motivos:
--     * obliga a bloques $$ que algunos clientes SQL no ejecutan bien;
--     * al restaurar el volcado del cliente sobre una base ya migrada, el disparador
--       pondria taller = false en todas las aulas del volcado, perdiendo el dato.
--   Cuando la version que solo lee 'taller' deje de existir, esa columna podra
--   eliminarse en una migracion posterior (fase 2).
--
-- Orden de aplicacion:
--   Esta migracion va ANTES del release que trae la pantalla nueva. Al ser
--   idempotente, se puede relanzar entera si algo falla a mitad.
--
-- Idempotente: se puede ejecutar mas de una vez sin efecto.
-- ============================================================================
BEGIN;

-- ---------------------------------------------------------------------------
-- 1) El catalogo
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sih.tipos_espacio (
    tipo_espacio_id bigint GENERATED BY DEFAULT AS IDENTITY,
    escuela_id      bigint NOT NULL,
    semestre_id     bigint NOT NULL,
    clase           character varying(20) NOT NULL,
    nombre          character varying(80) NOT NULL,
    activo          boolean DEFAULT true NOT NULL,
    creado          timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tipos_espacio_pk PRIMARY KEY (tipo_espacio_id),
    CONSTRAINT tipos_espacio_clase_ck CHECK (clase IN ('LABORATORIO', 'TALLER')),
    CONSTRAINT tipos_espacio_unico UNIQUE (semestre_id, clase, nombre),
    CONSTRAINT tipos_espacio_semestre_fk FOREIGN KEY (semestre_id)
        REFERENCES sih.semestre (semestre_id)
);

COMMENT ON TABLE sih.tipos_espacio IS
    'Tipos de laboratorio y taller por escuela y semestre. Uno por aula como maximo.';
COMMENT ON COLUMN sih.tipos_espacio.clase IS
    'LABORATORIO o TALLER. Sirve para agrupar en la pantalla y en los reportes.';

-- ---------------------------------------------------------------------------
-- 2) El aula apunta a su tipo (NULL = aula normal)
-- ---------------------------------------------------------------------------
ALTER TABLE sih.aulas ADD COLUMN IF NOT EXISTS tipo_espacio_id bigint;

ALTER TABLE sih.aulas DROP CONSTRAINT IF EXISTS aulas_tipo_espacio_fk;
ALTER TABLE sih.aulas ADD CONSTRAINT aulas_tipo_espacio_fk
    FOREIGN KEY (tipo_espacio_id) REFERENCES sih.tipos_espacio (tipo_espacio_id);

CREATE INDEX IF NOT EXISTS aulas_tipo_espacio_idx ON sih.aulas (tipo_espacio_id);

COMMENT ON COLUMN sih.aulas.tipo_espacio_id IS
    'Laboratorio o taller al que pertenece el aula. NULL = aula normal.';

-- ---------------------------------------------------------------------------
-- 2b) El tipo de un aula tiene que ser de SU semestre
--
-- Esto es lo que impide el error de fondo: un aula del semestre 11 apuntando a un tipo del
-- semestre 14. Con MATCH SIMPLE (el defecto), si tipo_espacio_id es NULL la restriccion no se
-- comprueba, que es justo lo que necesitan las aulas normales.
-- ---------------------------------------------------------------------------
ALTER TABLE sih.tipos_espacio DROP CONSTRAINT IF EXISTS tipos_espacio_semestre_tipo_unico;
ALTER TABLE sih.tipos_espacio ADD CONSTRAINT tipos_espacio_semestre_tipo_unico
    UNIQUE (semestre_id, tipo_espacio_id);

ALTER TABLE sih.aulas DROP CONSTRAINT IF EXISTS aulas_tipo_del_semestre_fk;
ALTER TABLE sih.aulas ADD CONSTRAINT aulas_tipo_del_semestre_fk
    FOREIGN KEY (semestre_id, tipo_espacio_id)
    REFERENCES sih.tipos_espacio (semestre_id, tipo_espacio_id);

-- ---------------------------------------------------------------------------
-- 3) Los cuatro tipos iniciales, en cada semestre que ya exista
-- ---------------------------------------------------------------------------
INSERT INTO sih.tipos_espacio (escuela_id, semestre_id, clase, nombre)
SELECT s.escuela_id, s.semestre_id, v.clase, v.nombre
FROM sih.semestre s
CROSS JOIN (VALUES
        ('LABORATORIO', 'Laboratorio de Cómputo'),
        ('LABORATORIO', 'Laboratorio de Química'),
        ('TALLER',      'Taller de Producción'),
        ('TALLER',      'Taller de Mecánica')
     ) AS v(clase, nombre)
ON CONFLICT DO NOTHING;

-- ---------------------------------------------------------------------------
-- 4) Las aulas que hoy estan marcadas como taller pasan a Laboratorio de Computo
--    (decision del 19/11/2026: es el tipo que se usa hoy; luego se reclasifican)
-- ---------------------------------------------------------------------------
UPDATE sih.aulas a
   SET tipo_espacio_id = t.tipo_espacio_id
  FROM sih.tipos_espacio t
 WHERE a.tipo_espacio_id IS NULL
   AND a.taller IS TRUE
   AND t.semestre_id = a.semestre_id
   AND t.clase = 'LABORATORIO'
   AND t.nombre = 'Laboratorio de Cómputo';

-- ---------------------------------------------------------------------------
-- 5) Entrada de menu, bajo Catalogos (26), visible para quien administra catalogos
--
-- menu_id es GENERATED ALWAYS: para escribir un id calculado hace falta
-- OVERRIDING SYSTEM VALUE, igual que en db/03_semilla.sql. No se usa el id
-- automatico a proposito: las semillas ya insertaron ids explicitos (25..45) y
-- la secuencia no se avanzo con ellos, asi que un id generado chocaria.
-- ---------------------------------------------------------------------------
INSERT INTO sih.menu (menu_id, pariente_id, nombre, ruta, icono, menu_orden, activo, creado, nivel)
OVERRIDING SYSTEM VALUE
SELECT COALESCE(MAX(menu_id), 0) + 1, 26, 'Lab / Taller', '/catalogo/tipos-espacio',
       'MdScience', 9, true, CURRENT_TIMESTAMP, 2
  FROM sih.menu
 WHERE NOT EXISTS (SELECT 1 FROM sih.menu WHERE ruta = '/catalogo/tipos-espacio');

INSERT INTO sih.rol_menu (rol_id, menu_id)
SELECT r.rol_id, m.menu_id
  FROM sih.roles r
 CROSS JOIN sih.menu m
 WHERE m.ruta = '/catalogo/tipos-espacio'
   AND r.nombre IN ('ADMIN', 'COORDINADOR', 'DIRECTOR')
ON CONFLICT DO NOTHING;

-- deja la secuencia por delante del id maximo, para que un alta desde la pantalla
-- de Menu no choque con los ids que metieron las semillas
SELECT setval(pg_get_serial_sequence('sih.menu', 'menu_id'),
              GREATEST((SELECT COALESCE(MAX(menu_id), 0) FROM sih.menu), 1));

COMMIT;
